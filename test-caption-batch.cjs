const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const js=fs.readFileSync('caption-batch-editor.js','utf8');
const css=fs.readFileSync('caption-batch-editor.css','utf8');
const app=fs.readFileSync('app.js','utf8');
const mobile=fs.readFileSync('mobile-v42.js','utf8');
const desktop=fs.readFileSync('desktop-ui.js','utf8');
const build=fs.readFileSync('build.cjs','utf8');

assert.ok(/caption-batch-editor\.js\?v=[^\"']+/.test(html),'whole-caption editor script missing');
assert.ok(/caption-batch-editor\.css\?v=[^\"']+/.test(html),'whole-caption editor css missing');
assert.ok(build.includes('runtimeRefs')&&build.includes('index.matchAll'),'build must derive caption batch assets from index.html');
assert.ok(js.includes('window.CutflowCaptionBatch={'),'shared whole-caption editor API missing');
assert.ok(js.includes('input.focus({preventScroll:true})'),'whole-caption editor must focus selected text without moving the dialog');
assert.ok(!js.includes("input.scrollIntoView({block:'nearest'})"),'whole-caption editor must not browser-scroll the dialog when selecting text');
assert.ok(css.includes('overflow-y:auto;overflow-x:hidden'),'whole-caption list must block horizontal viewport drift');
assert.ok(css.includes('flex-wrap:wrap')&&css.includes('overflow-wrap:anywhere'),'whole-caption segments must wrap onto new lines instead of horizontal scrolling');
assert.ok(js.includes('sceneApi()?.items?.()'),'whole-caption editor must group by logical scenes');
assert.ok(js.includes('caption-batch-row'),'scene row UI missing');
assert.ok(js.includes('caption-batch-divider'),'slash divider UI missing');
assert.ok(!js.includes('start.toFixed')&&!js.includes('end.toFixed'),'whole-caption editor should not show time codes');
assert.ok(js.includes("api()?.split?.(selected,cursor)"),'cursor split missing');
assert.ok(js.includes("api()?.mergeNext?.(target)"),'merge previous workflow missing');
assert.ok(js.includes("api()?.mergeNext?.(selected)"),'merge next workflow missing');
assert.ok(js.includes("api()?.remove?.(selected)"),'caption delete workflow missing');
assert.ok(js.includes('data-caption-batch-auto-wrap'),'batch auto-wrap action missing');
assert.ok(js.includes('window.CutflowAutoBridge?.autoWrapCaptions'),'batch editor must reuse shared auto-wrap logic');
assert.ok(css.includes('caption-batch-auto-wrap'),'batch auto-wrap control styling missing');
assert.ok(app.includes('const firstDuration=Math.max(.1,Math.min(duration-.1,duration*ratio))')&&app.includes('splitAt=start+firstDuration'),'caption split must stay inside the existing time range');
assert.ok(app.includes('const end=Number(next.end)')&&app.includes('c.end=end'),'caption merge must preserve the combined narration time range');
assert.ok(desktop.includes('desktopBatchCaptions'),'desktop whole-caption entry missing');
assert.ok(mobile.includes('v42CaptionBatchOpen'),'mobile whole-caption entry missing');
assert.ok(css.includes('@media(max-width:760px)'),'mobile whole-caption layout missing');
assert.ok(css.includes('white-space:nowrap'),'one-line caption rows missing');
assert.ok(js.includes("dialog.addEventListener('cancel'")&&js.includes('commitDraft()')&&js.includes("?.blur?.()"),'batch editor must commit draft and release iPhone focus on cancel');
assert.ok(js.includes("String(state.text||'').trim()"),'deleted caption gaps should be hidden from compact batch rows');
console.log('PASS: shared whole-caption editor v1 is wired for PC/mobile and preserves caption timing ranges.');
