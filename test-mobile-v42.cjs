const fs=require('node:fs'),assert=require('node:assert');
const html=fs.readFileSync('index.html','utf8');
const js=fs.readFileSync('mobile-v42.js','utf8');
const css=fs.readFileSync('mobile-v42.css','utf8');
const build=fs.readFileSync('build.cjs','utf8');
assert(html.includes('mobile-v42.css?v=42'),'v42 mobile css not loaded');
assert(html.includes('mobile-v42.js?v=42'),'v42 mobile js not loaded');
assert(!html.includes('mobile-ui.css?v='),'legacy mobile-ui.css must not load');
assert(!html.includes('mobile-ui.js?v='),'legacy mobile-ui.js must not load');
assert(!html.includes('mobile-fullscreen.js?v='),'legacy mobile-fullscreen.js must not load');
assert(!html.includes('mobile-fullscreen.css?v='),'legacy mobile-fullscreen.css must not load');
assert(js.includes("app.id='mobileAppV42'"),'independent mobile app missing');
assert(js.includes("document.body.classList.add('v42-mobile')"),'mobile mode class missing');
assert(!js.includes("move(q('.source-panel')")&&!js.includes('mobile-original-position'),'v42 must not move desktop panels');
assert(js.includes('data-click="projectOpenBtn"')&&js.includes('data-click="projectSaveBtn"')&&js.includes('data-click="exportBtn"'),'top project proxies missing');
for(const tab of ['caption','media','narration','template','bgm'])assert(js.includes(`data-tab="${tab}"`),`missing ${tab} tab`);
assert(js.includes('CutflowScene?.select')&&js.includes('CutflowScene?.replace'),'scene bridge missing');
assert(js.includes('transformScale')&&js.includes('transformX')&&js.includes('transformY'),'media transform proxies missing');
assert(js.includes('scriptInput')&&js.includes('buildCuesBtn')&&js.includes('CutflowSilenceCut.process'),'narration workflow bridge missing');
assert(js.includes('autoGridBtn')&&js.includes('autoSingleBtn')&&js.includes('autoStart'),'auto setup bridge missing');
assert(js.includes('layoutSelect')&&js.includes('titleInput')&&js.includes('channelInput'),'template bridge missing');
assert(js.includes('bgmVolume')&&js.includes('bgmFadeIn')&&js.includes('bgmFadeOut'),'BGM bridge missing');
assert(js.includes('v42PreviewDialog')&&js.includes('v42FullStage'),'fullscreen preview missing');
assert(css.includes('body.v42-mobile>header.topbar')&&css.includes('body.v42-mobile>main.app-shell'),'desktop root fail-safe missing');
assert(build.includes("'mobile-v42.js','mobile-v42.css'")&&!build.includes("'mobile-ui.js','mobile-ui.css'"),'build must publish v42, not legacy mobile UI');
console.log('Cutflow v42 independent mobile shell checks passed');
